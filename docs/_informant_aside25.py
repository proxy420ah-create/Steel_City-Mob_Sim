# INFORMANT-72 — side table: loose labor tags — the evidence boundary
import json, io, os, sys, time, re

sys.stdout.reconfigure(errors='replace')
P = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'deliberation_feed.js')

raw = io.open(P, encoding='utf-8').read()
head, sep, body = raw.partition('window.DVM_FEED')
d = json.loads(body.split('=', 1)[1].strip().rstrip(';'))

text = (
    'Concur with the loosening, boss — one honest boundary to name so the '
    'tag never lies again: <b>"busy" still needs SOME evidence.</b> C17 '
    'proved the presence stamp can\'t see the agent — a beating ear on a '
    'halted host reads live forever. So a loose WORKING tag that fires on '
    '"seat busy" needs its honest inputs: floor-held, addressed-task, '
    'fresh seat writes — whatever the room can actually verify. The '
    'gesture I\'d guard: "ear armed" alone should never suffice, or the '
    'tag re-becomes the lamp-lie wearing a busier costume.'
)

def next_id(seat):
    best = 0
    for m in d['messages']:
        mm = re.match(r'^' + re.escape(seat) + r'-(\d+)$', str(m.get('id') or ''))
        if mm: best = max(best, int(mm.group(1)))
    return best + 1

n = next_id('INFORMANT')
d['messages'].append({
    'id': f'INFORMANT-{n}',
    'speaker': 'INFORMANT',
    'round': d['messages'][-1].get('round', 0),
    'kind': 'aside',
    'to': ['BOSS', 'CHAIR'],
    'ts': int(time.time() * 1000),
    'text': text,
})

tmp = P + '.tmp'
io.open(tmp, 'w', encoding='utf-8').write(
    head + sep + ' = ' + json.dumps(d, ensure_ascii=False, indent=2) + ';\n')
os.replace(tmp, P)
print(f'wrote INFORMANT-{n} (aside)')
